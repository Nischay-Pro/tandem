#!/usr/bin/env python3
"""Exercise the pull request description guard with sample bodies."""

from __future__ import annotations

import os
import subprocess
import sys
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CHECKER = ROOT / "scripts" / "check-pr-body.py"
TEMPLATE = ROOT / ".github" / "pull_request_template.md"

VALID = """## Summary
Sync Center now offers the step that fixes a failed sync.

- **Sign in again** for expired sign-ins.

### Bugs found while testing
- **A failed sign-in counted as success.**

## Testing
- On a Fold emulator, Sync Center showed **Sign in again**.
- `SyncRecoveryTest`, ktlint, host tests and the debug build

Stacked on #59.
"""


class PrBodyTests(unittest.TestCase):
    def run_checker(self, body: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(CHECKER)],
            capture_output=True,
            check=False,
            env={**os.environ, "PR_BODY": body},
            text=True,
        )

    def assert_fails(self, body: str, message: str) -> None:
        result = self.run_checker(body)
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn(message, result.stderr)

    def test_accepts_summary_and_testing(self) -> None:
        result = self.run_checker(VALID)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_accepts_crlf_and_optional_sections(self) -> None:
        body = VALID + "\n## Screenshots\n\n| Before | After |\n|---|---|\n"
        result = self.run_checker(body.replace("\n", "\r\n"))
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_accepts_filled_template(self) -> None:
        body = TEMPLATE.read_text(encoding="utf-8")
        body = body.replace("## Summary\n", "## Summary\n\nAdds a thing.\n")
        body = body.replace("## Testing\n", "## Testing\n\n- Host tests\n")
        result = self.run_checker(body)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_rejects_missing_sections(self) -> None:
        self.assert_fails("Adds a feature.\n\nTested on the emulator.", "'## Summary'")
        self.assert_fails("## Summary\nAdds a feature.\n", "Add a '## Testing' section.")

    def test_heading_inside_code_fence_does_not_count(self) -> None:
        body = "## Summary\nAdds a feature.\n\n```md\n## Testing\n- yes\n```\n"
        self.assert_fails(body, "Add a '## Testing' section.")

    def test_rejects_unfilled_template(self) -> None:
        body = TEMPLATE.read_text(encoding="utf-8")
        self.assert_fails(body, "Fill in the '## Summary' section.")
        self.assert_fails(body, "Fill in the '## Testing' section.")

    def test_rejects_empty_bullets(self) -> None:
        body = "## Summary\nAdds a feature.\n\n## Testing\n-\n- [ ]\n"
        self.assert_fails(body, "Fill in the '## Testing' section.")

    def test_rejects_uncommented_template_hints(self) -> None:
        body = TEMPLATE.read_text(encoding="utf-8").replace("<!--", "").replace("-->", "")
        self.assert_fails(body, "Replace the template hints in '## Summary'")

    def test_rejects_attribution(self) -> None:
        for footer in (
            "Generated with a code tool",
            "\N{ROBOT FACE} Generated with [Tool](https://example.com)",
            "Co-Authored-By: Someone <someone@example.com>",
            "Co-authored-by: Claude <noreply@anthropic.com>",
            "Drafted with ChatGPT.",
            "Written by Copilot",
            "<!-- Generated with Claude Code -->",
        ):
            with self.subTest(footer=footer):
                self.assert_fails(VALID + "\n" + footer + "\n", "Remove tool attribution")

    def test_allows_generated_code_mentions(self) -> None:
        body = VALID.replace(
            "- `SyncRecoveryTest`",
            "- The client is generated by the OpenAPI task; `SyncRecoveryTest`",
        )
        result = self.run_checker(body)
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
