internal fun AppRoute.isSetupRoute(): Boolean =
    this in
        setOf(
            AppRoute.WELCOME,
            AppRoute.SERVER_ADDRESS,
            AppRoute.SIGN_IN,
            AppRoute.BUDGET_CHOOSER,
            AppRoute.BUDGET_UNLOCK,
            AppRoute.FIRST_SYNC,
            AppRoute.PERSONALIZE,
            AppRoute.SETUP_COMPLETE,
        )
